// One-off: embed the white wordmark in code for the order emails, sized for a
// 120px-wide header at 2x. Emails attach it inline (cid:) rather than linking
// to zode.org, which the same-origin CORP header would block.
// Kept in code, not read from public/, so it ships with the serverless function.
const fs = require("fs");
const path = require("path");
const sharp = require("sharp");

(async () => {
  const src = path.join(__dirname, "..", "public", "wordmark.png");
  const png = await sharp(src).resize({ width: 240 }).png({ compressionLevel: 9, palette: true }).toBuffer();
  const out = path.join(__dirname, "..", "src", "emails", "wordmark.ts");
  fs.writeFileSync(
    out,
    `// Generated by scripts/make-email-wordmark.cjs from public/wordmark.png; do not edit.\n` +
      `export const WORDMARK_PNG_BASE64 =\n  "${png.toString("base64")}";\n`,
  );
  console.log(`wrote ${path.relative(process.cwd(), out)} (${png.length} bytes)`);
})();
